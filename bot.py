async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    user_id = update.effective_user.id
    user_state.setdefault(user_id, {})

    keyboard = InlineKeyboardMarkup(
        [[InlineKeyboardButton("🚀 Boshlash / Начать", callback_data="begin")]]
    )
    await update.message.reply_photo(
        photo=io.BytesIO(get_welcome_image_bytes()),
        caption=(
            "Salom! 👋 Men — Repetitor AI, matematikadan yordamchi botman.\n"
            "Привет! Я — бот-помощник по математике.\n\n"
            "Boshlash uchun tugmani bos / Нажми кнопку, чтобы начать 👇"
        ),
        reply_markup=keyboard,
    )


async def on_begin(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    query = update.callback_query
    await query.answer()
    keyboard = InlineKeyboardMarkup(
        [
            [InlineKeyboardButton("🇺🇿 O'zbekcha", callback_data="lang:uz")],
            [InlineKeyboardButton("🇷🇺 Русский", callback_data="lang:ru")],
        ]
    )
    await query.message.reply_text(
        "Qaysi tilda ishlaylik? / На каком языке будем заниматься?",
        reply_markup=keyboard,
    )


async def on_lang(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    query = update.callback_query
    await query.answer()
    user_id = update.effective_user.id
    lang = query.data.split(":", 1)[1]
    user_state.setdefault(user_id, {})["lang"] = lang
    t = TEXTS[lang]

    keyboard = InlineKeyboardMarkup(
        [[InlineKeyboardButton(t["grade_label"].format(g=g), callback_data=f"grade:{g}")]
         for g in GRADES]
    )
    await query.message.reply_text(t["choose_grade"], reply_markup=keyboard)


async def on_grade(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    query = update.callback_query
    await query.answer()
    user_id = update.effective_user.id
    grade = query.data.split(":", 1)[1]
    lang = lang_of(user_id)
    user_state.setdefault(user_id, {})["grade"] = grade
    t = TEXTS[lang]

    await query.message.reply_text(t["grade_set"].format(g=grade))


async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    user_id = update.effective_user.id
    text = update.message.text
    state = user_state.get(user_id, {})
    lang = state.get("lang", "uz")
    grade = state.get("grade")
    t = TEXTS[lang]

    if not grade:
        await update.message.reply_text(t["need_grade"])
        return

    if client is None:
        await update.message.reply_text(t["not_configured"])
        return

    await context.bot.send_chat_action(chat_id=update.effective_chat.id, action="typing")

    try:
        response = client.chat.completions.create(
            model=GROQ_MODEL,
            max_tokens=700,
            temperature=0.2,  # aniq, xatosiz hisob-kitob uchun past harorat
            messages=[
                {"role": "system", "content": t["system_prompt"].format(grade=grade)},
                {"role": "user", "content": text},
            ],
        )
        answer = response.choices[0].message.content
        try:
            await update.message.reply_text(answer, parse_mode="Markdown")
        except Exception:
            # AI javobida Telegram Markdown'ni buzadigan belgi bo'lsa,
            # oddiy matn sifatida yuboramiz (formatlashsiz, lekin ishlaydi)
            await update.message.reply_text(answer)
    except Exception:
        logger.exception("AI javob berishda xatolik")
        await update.message.reply_text(t["error"])


